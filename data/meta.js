window.CARDS = [];

window.addCards = function addCards(lesson, deck, type, section, page, items, defaults) {
  const key = `${lesson}|${deck}`;
  const counters = window.addCards.counters || (window.addCards.counters = {});
  items.forEach(item => {
    counters[key] = (counters[key] || 0) + 1;
    const [first, second, extra] = item;
    const card = Object.assign({
      id: `gs-l${String(lesson).padStart(2, "0")}-${deck}-${String(counters[key]).padStart(3, "0")}`,
      lesson, deck, type, section, page
    }, defaults || {});
    if (type === "form") {
      card.sr = first;   // исходная форма (сербский)
      card.ans = second; // нужная форма (сербский)
    } else {
      card.sr = first;   // сербский, кириллицей
      card.ru = second;  // перевод
    }
    Object.assign(card, extra || {});
    window.CARDS.push(card);
  });
};
